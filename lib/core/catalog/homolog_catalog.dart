  // SEED/MOCK/HOMOLOGAÇÃO — locação
  static List<RentalModel> filterRentals(
    List<RentalModel> all, {
    RentalKind? kind,
    String? category,
    String? query,
    bool availableOnly = false,
  }) {
    var list = List<RentalModel>.from(all);
    if (kind != null) {
      list = list.where((r) => r.kind == kind).toList();
    }
    if (category != null && category.isNotEmpty) {
      list = list.where((r) => r.category == category).toList();
    }
    if (query != null && query.trim().isNotEmpty) {
      final q = query.trim().toLowerCase();
      list = list
          .where((r) =>
              r.title.toLowerCase().contains(q) ||
              (r.brand ?? '').toLowerCase().contains(q) ||
              (r.model ?? '').toLowerCase().contains(q) ||
              (r.city ?? '').toLowerCase().contains(q) ||
              r.ownerName.toLowerCase().contains(q))
          .toList();
    }
    if (availableOnly) {
      list = list.where((r) => r.available).toList();
    }
    return list;
  }

  static List<RentalModel> rentals({
    RentalKind? kind,
    String? category,
    String? query,
    bool? availableOnly,
  }) {
    if (!enabled) return const [];
    return filterRentals(
      _rentalSeed,
      kind: kind,
      category: category,
      query: query,
      availableOnly: availableOnly ?? false,
    );
  }

