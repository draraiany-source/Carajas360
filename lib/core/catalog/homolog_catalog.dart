  /// Pure filter used by [providers] and unit tests (no Firebase).
  static List<ProviderModel> matchProviders(
    List<ProviderModel> all, {
    String? category,
    String? group,
    required Set<String> groupIds,
  }) {
    if (category != null && category.isNotEmpty) {
      return all.where((p) => p.categories.contains(category)).toList();
    }
    if (group != null && group.isNotEmpty && group != 'Todos') {
      return all.where((p) => p.categories.any(groupIds.contains)).toList();
    }
    return List<ProviderModel>.from(all);
  }

  /// Exact category id match only (never fuzzy contains).
  static List<ProviderModel> providers({String? category, String? group}) {
    if (!enabled) return const [];
    final groupIds = (group != null && group.isNotEmpty && group != 'Todos')
        ? Categories.all.where((c) => c.group == group).map((c) => c.id).toSet()
        : <String>{};
    return matchProviders(
      _seed,
      category: category,
      group: group,
      groupIds: groupIds,
    );
  }

  static List<ProviderModel> filter({
    String? category,
    String? group,
    String query = '',
    bool onlineOnly = false,
    bool presentialOnly = false,
  }) {
    var list = providers(category: category, group: group);
    if (query.trim().isNotEmpty) {
      final q = query.toLowerCase();
      list = list
          .where((p) =>
              p.name.toLowerCase().contains(q) ||
              p.categories.any((c) => c.toLowerCase().contains(q)) ||
              (p.bio?.toLowerCase().contains(q) ?? false) ||
              (p.city?.toLowerCase().contains(q) ?? false))
          .toList();
    }
    if (onlineOnly) {
      list = list.where((p) => p.modalities.contains('online')).toList();
    }
    if (presentialOnly) {
      list = list.where((p) => p.modalities.contains('presential')).toList();
    }
    return list;
  }

  /// Health domain only — never mix with general services list.
  /// mode: 0 all, 1 online, 2 presential, 3 home_care
  static List<ProviderModel> healthProviders({
    String? specialty,
    int mode = 0,
    String query = '',
  }) {
    if (!enabled) return const [];
    var list = List<ProviderModel>.from(_healthSeed);
    if (specialty != null && specialty.isNotEmpty) {
      list = list.where((p) => p.categories.contains(specialty)).toList();
    }
    switch (mode) {
      case 1:
        list = list.where((p) => p.modalities.contains('online')).toList();
        break;
      case 2:
        list = list.where((p) => p.modalities.contains('presential')).toList();
        break;
      case 3:
        list = list
            .where((p) =>
                p.categories.contains('home_care') ||
                p.modalities.contains('home_care'))
            .toList();
        break;
    }
    if (query.trim().isNotEmpty) {
      final q = query.toLowerCase();
      list = list
          .where((p) =>
              p.name.toLowerCase().contains(q) ||
              p.categories.any((c) => c.toLowerCase().contains(q)) ||
              (p.bio?.toLowerCase().contains(q) ?? false))
          .toList();
    }
    return list;
  }

